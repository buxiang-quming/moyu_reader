def _build():
    s2t = {}
    t2s = {}
    for tok in _PAIRS.split():
        if len(tok) != 2:
            raise ValueError("简繁配对标定错误：%r" % tok)
        s, t = tok[0], tok[1]
        if s == t:
            continue
        s2t[ord(s)] = t
        t2s.setdefault(ord(t), s)
    # 一繁对多简的补充（不含歧义字）
    for a, b in (("麽", "么"), ("祇", "只"), ("喫", "吃")):
        t2s.setdefault(ord(a), b)
    return s2t, t2s


S2T, T2S = _build()
_T_SET = set(chr(k) for k in T2S)
_S_SET = set(chr(k) for k in S2T)


def convert(text, mode):
    """mode: none | t2s（繁转简） | s2t（简转繁）"""
    if not text or mode not in ("t2s", "s2t"):
        return text
    table = T2S if mode == "t2s" else S2T
    return text.translate(table)


def has_traditional(text):
    """粗略判断文本是否含繁体字（用于导入时提示）。"""
    sample = text[:4000]
    hits = 0
    for ch in sample:
        if ch in _T_SET:
            hits += 1
            if hits >= 8:
                return True
    return False
